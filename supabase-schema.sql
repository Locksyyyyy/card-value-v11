create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  plan text not null default 'free',
  stripe_customer_id text,
  created_at timestamptz not null default now()
);
create table if not exists public.collection_cards (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  card_id text,
  name text not null,
  set_name text,
  card_number text,
  rarity text,
  variant text,
  language text,
  condition text,
  value numeric(12,2) not null default 0,
  image text,
  metadata jsonb,
  created_at timestamptz not null default now()
);
create table if not exists public.usage_monthly (
  user_id uuid not null references auth.users(id) on delete cascade,
  month date not null,
  scans integer not null default 0,
  primary key(user_id,month)
);
alter table public.profiles enable row level security;
alter table public.collection_cards enable row level security;
alter table public.usage_monthly enable row level security;
create policy "profile self read" on public.profiles for select using (auth.uid()=id);
create policy "collection self" on public.collection_cards for all using (auth.uid()=user_id) with check (auth.uid()=user_id);
create policy "usage self read" on public.usage_monthly for select using (auth.uid()=user_id);
create or replace function public.handle_new_user() returns trigger language plpgsql security definer set search_path=public as $$ begin insert into public.profiles(id) values(new.id) on conflict do nothing; return new; end; $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();
